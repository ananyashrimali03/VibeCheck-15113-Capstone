/** Theme id for debugging / transitions — derived from inference copy, not user-controlled. */
export type VibeThemeId =
  | "default"
  | "calm"
  | "energetic"
  | "melancholy"
  | "cozy"
  | "stormy"
  | "bright"
  | "night"
  | "focus"
  | "romantic"
  | "playful";

export type VibeTheme = {
  id: VibeThemeId;
  /** Flat CSS custom properties for the shell + session UI */
  vars: CSSProperties;
};

function corpus(r: InferenceResult): string {
  return [
    r.mood_label,
    r.playlist_vibe,
    r.playlist_title,
    r.weather_metaphor,
    r.notification_line,
    r.deezer_search_query,
    r.moment_arc,
  ]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
}

/** Stronger signals first when scores tie */
const TIE_ORDER: VibeThemeId[] = [
  "stormy",
  "melancholy",
  "night",
  "energetic",
  "playful",
  "romantic",
  "cozy",
  "bright",
  "focus",
  "calm",
  "default",
];

const KEYWORDS: Record<Exclude<VibeThemeId, "default">, readonly string[]> = {
  calm: ["calm", "peace", "rest", "gentle", "soft", "quiet", "ease", "zen", "still", "breathe"],
  energetic: ["energy", "pump", "hype", "party", "loud", "upbeat", "dance", "club", "fast", "rush"],
  melancholy: ["melanch", "sad", "blue", "nostalg", "wistful", "lonely", "grief", "heavy heart"],
  cozy: ["cozy", "warm", "blanket", "coffee", "home", "comfort", "sweater", "fireplace"],
  stormy: ["storm", "rain", "grey", "gray", "thunder", "wind", "cloud", "drizzle", "fog"],
  bright: ["bright", "sun", "summer", "shine", "golden", "morning", "daylight", "clear sky"],
  night: ["night", "late", "midnight", "moon", "neon", "city lights", "after dark", "insomnia"],
  focus: ["focus", "study", "deep", "flow", "grind", "work", "deadline", "locked in"],
  romantic: ["romantic", "love", "crush", "date", "heart", "slow dance", "intimate"],
  playful: ["playful", "fun", "silly", "goofy", "lightheart", "whims", "bounce"],
};

function pickThemeId(text: string): VibeThemeId {
  let best: VibeThemeId = "default";
  let bestScore = -1;
  const entries = Object.entries(KEYWORDS) as [Exclude<VibeThemeId, "default">, readonly string[]][];
  for (const [id, words] of entries) {
    let score = 0;
    for (const w of words) {
      if (text.includes(w)) score += 1;
    }
    if (score === 0) continue;
    if (score > bestScore) {
      bestScore = score;
      best = id;
    } else if (score === bestScore) {
      const ni = TIE_ORDER.indexOf(id);
      const nb = TIE_ORDER.indexOf(best);
      if (ni !== -1 && nb !== -1 && ni < nb) best = id;
    }
  }
  if (bestScore <= 0) return "default";
  return best;
}

