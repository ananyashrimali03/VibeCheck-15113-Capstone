function mergeVars(id: VibeThemeId): Record<string, string> {
  const base = { ...BASE_VARS } as Record<string, string>;
  const patch = PATCHES[id];
  for (const k of Object.keys(patch)) {
    const key = k as keyof typeof BASE_VARS;
    const v = patch[key];
    if (v !== undefined) base[key] = v;
  }
  const a = ACCENTS[id];
  base["--vc-saturate"] = a.saturate;
  base["--vc-hue-rotate"] = a.hueRotate;
  base["--vc-radius-bump"] = a.radiusBump;
  return base;
}

export function resolveVibeTheme(inference: InferenceResult): VibeTheme {
  let id = pickThemeId(corpus(inference));
  if (inference.safety.distress_hint) {
    id = "calm";
  }
  const vars = mergeVars(id) as unknown as CSSProperties;
  return { id, vars };
}
